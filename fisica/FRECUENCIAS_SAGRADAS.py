def obtener_armónico(frecuencia_base: float, n: int) -> float:
    """
    Calcula el n-ésimo armónico de una frecuencia base.
    
    Args:
        frecuencia_base: Frecuencia fundamental en Hz
        n: Número de armónico (1 = fundamental, 2 = segunda armónica, etc.)
    
    Returns:
        Frecuencia del armónico en Hz
    """
    return frecuencia_base * n


def es_armónico_de_f0(frecuencia: float, tolerancia: float = 0.05) -> tuple[bool, float]:
    """
    Verifica si una frecuencia es armónica de f₀ = 141.7001 Hz.
    
    Args:
        frecuencia: Frecuencia a verificar en Hz
        tolerancia: Tolerancia relativa para considerar armónico (default 5%)
    
    Returns:
        Tupla (es_armónico, razón) donde:
        - es_armónico: True si es armónico dentro de la tolerancia
        - razón: Razón frecuencia/f₀
    """
    razon = frecuencia / F0_HZ
    razon_entera = round(razon)
    error_relativo = abs(razon - razon_entera) / razon_entera if razon_entera != 0 else 1.0
    es_armónico = error_relativo < tolerancia
    return es_armónico, razon


